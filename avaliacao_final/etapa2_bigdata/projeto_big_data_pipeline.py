"""### ETAPA 2: CRIAÇÃO DA RAW"""

print("=" * 70)
print("ETAPA 2 — RAW")
print("=" * 70)

df = df_raw.copy()

# Padronização dos nomes
df.columns = (
    df.columns
    .str.strip()
    .str.lower()
)

# IDs
df["transaction_id"] = pd.to_numeric(
    df["transaction_id"],
    errors="coerce"
).astype("Int64")

df["customer_id"] = pd.to_numeric(
    df["customer_id"],
    errors="coerce"
).astype("Int64")

# Valores numéricos
df["amount"] = pd.to_numeric(
    df["amount"],
    errors="coerce"
)

df["risk_score"] = pd.to_numeric(
    df["risk_score"],
    errors="coerce"
)

df["credit_score"] = pd.to_numeric(
    df["credit_score"],
    errors="coerce"
).astype("Int64")

# Data
df["timestamp"] = pd.to_datetime(
    df["timestamp"],
    errors="coerce"
)

# Variáveis categóricas
colunas_categoricas = [
    "transaction_type",
    "channel",
    "merchant_category",
    "status",
    "segment"
]

for coluna in colunas_categoricas:

    df[coluna] = (
        df[coluna]
        .astype("string")
        .str.strip()
        .str.lower()
    )

# Variável de fraude
df["is_fraud"] = (
    df["is_fraud"]
    .astype("string")
    .str.lower()
    .map({
        "true": True,
        "false": False,
        "1": True,
        "0": False,
        "yes": True,
        "no": False
    })
)

print("Tipos definidos:")
display(
    pd.DataFrame({
        "coluna": df.columns,
        "tipo": df.dtypes.astype(str)
    })
)

