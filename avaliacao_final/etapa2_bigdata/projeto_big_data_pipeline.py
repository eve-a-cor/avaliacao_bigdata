"""### Silver: período do dia"""

def classificar_periodo(hora):

    if 6 <= hora < 12:
        return "manhã"

    elif 12 <= hora < 18:
        return "tarde"

    elif 18 <= hora < 24:
        return "noite"

    else:
        return "madrugada"


silver["periodo_dia"] = (
    silver["timestamp"]
    .dt.hour
    .apply(classificar_periodo)
)

display(
    silver["periodo_dia"]
    .value_counts()
    .to_frame("quantidade")
)

